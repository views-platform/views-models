import importlib.util
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
INSTALLED_HYDRANET = (
    REPO_ROOT / "envs" / "views-hydranet" / "lib" / "python3.11"
    / "site-packages" / "views_hydranet"
)


def _declared_hp_keys(model_dir: Path) -> set[str]:
    """Load a source's hyperparameter keys from SOURCE, never via __pycache__."""
    hp = model_dir / "configs" / "config_hyperparameters.py"
    spec = importlib.util.spec_from_file_location(f"_hp_{model_dir.name}", hp)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return set(module.get_hp_config().keys())


def _hydranet_sources() -> list[Path]:
    out = []
    for req in sorted(REPO_ROOT.glob("models/*/requirements.txt")):
        if re.search(r"^views-hydranet", req.read_text(), re.MULTILINE):
            out.append(req.parent)
    return out


HYDRANET_SOURCES = _hydranet_sources()


def test_the_census_is_not_vacuous():
    """If this file stops finding HydraNet sources, every assertion below is meaningless.

    Absence is not a pass: a check that cannot see its subject must fail, not report clean.
    """
    assert len(HYDRANET_SOURCES) >= 10, (
        f"only {len(HYDRANET_SOURCES)} HydraNet sources found — the glob or the "
        f"requirements convention changed, so the findings below are unverifiable"
    )
    assert INSTALLED_HYDRANET.is_dir(), (
        f"{INSTALLED_HYDRANET} is absent. This suite cannot tell a consumed key from an "
        f"inert one without the library it is pinned against. FAILING rather than passing."
    )


# ── Finding 1 — hard falsification of clause (c) ──────────────────────────────
#
# `h_init` was declared by 15 sources and read by nothing. Measured 2026-10-24 against
# PARTIALLY ADDRESSED 2026-10-24 (PR #603): deleted from the seven sources that carry no
# pinned experimental contrast, in config_hyperparameters.py AND config_sweep.py. This
# assertion still fails, naming the remaining EIGHT, and that is correct — it is not a
# stale failure. Those eight form the experiment chain and `h_init` is in neither
# ARM_FREE_KEYS nor REPLICATE_FREE_KEYS, so the fix is one atomic edit across all eight
# including violet_visitor, or none. Do not narrow the census to make this green.
# views-hydranet 0.1.5 (installed) AND 0.1.7 (current PyPI, downloaded and inspected):
#
#   grep -rn "h_init"       views_hydranet/  ->  0 hits in both
#   grep -rn "abs_rand_exp" views_hydranet/  ->  0 hits in both
#
# and the hidden state is initialised unconditionally:
#
#   def init_hTtime(self, hidden_channels, H, W):
#       hs = torch.zeros((1, hidden_channels, H, W), dtype=torch.float32)
#       return hs
#
# `HydraNetConfig.model_config` is `extra="allow"`, so the key validates silently. The config
# asserts a hidden-state initialisation scheme ('abs_rand_exp-100') that does not exist in any
# released version of the library.
#
# Registered as instance (5) of **C-157** in this repo's register — "a dead key, a missing key
# and a look-alike key all pass every check". Its instance (3) is `force_target_only`, the same
# shape in views-r2darts2. (An earlier draft of this file cited "C-324"; that ID belongs to
# views-hydranet's register, not this one, and naming it here would have sent a reader to the
# wrong document.)
#
# Either the library should implement it, or the sources should stop claiming it. Both are
# "a further change", which is what clause (c) denies.

def test_no_hydranet_source_declares_a_key_the_pinned_library_never_reads():
    """A declared key that nothing consumes is a config that lies about the model.

    Scoped deliberately to `h_init`: it is the one key this audit traced end to end, and a
    blanket "every key must be consumed" assertion would fire on keys that pipeline-core
    reads rather than views-hydranet (`skip_predictions_delivery` is the documented example,
    config_initializer.py:1535). Widen only with the same evidence per key.
    """
    package_text = "\n".join(
        p.read_text(errors="replace")
        for p in INSTALLED_HYDRANET.rglob("*.py")
        if "__pycache__" not in p.parts
    )
    assert package_text, "read no library source — refusing to report a clean result"

    consumed = "h_init" in package_text
    offenders = sorted(
        d.name for d in HYDRANET_SOURCES if "h_init" in _declared_hp_keys(d)
    )

    assert consumed or not offenders, (
        f"{len(offenders)} source(s) declare 'h_init' and the pinned views-hydranet never "
        f"reads it, so the hidden state is always torch.zeros regardless of the value "
        f"declared:\n  {offenders}\n"
        f"Fix by implementing it in views-hydranet or deleting the key from these configs. "
        f"Do not silence this by narrowing the census."
    )


# ── Finding 2 — soft falsification of clause (c) ──────────────────────────────
#
# `views-hydranet~=0.1.1` means ">=0.1.1, ==0.1.*". On 2026-10-24 that range admits every
# release up to 0.1.7, published 2026-10-23T23:53Z. The env on this machine holds 0.1.5.
# run.sh's up-to-date check (`pip install --dry-run`, counting lines that are not
# "Requirement already satisfied") treats 0.1.5 as satisfying the range, so an existing env
# is left alone while a FRESH env resolves 0.1.7.
#
# Two launches of a byte-identical config therefore run different library code, decided by
# the age of the env rather than by anything declared. That is the C-167 confound: it already
# cost a confounded sigma-hat once, when 0.1.4 landed 1h20m before a run started.
#
# 0.1.7 is additive against 0.1.5 for this config (0 fields removed, 2 added:
# emit_distribution, trajectory_log_path), so nothing breaks today. The finding is that
# nothing in the repo would have told us if it were not additive.

EXPECTED_HYDRANET_SPEC_IS_EXACT = False  # flips to True when the pin is tightened


def test_the_hydranet_pin_does_not_admit_an_unvalidated_library_version():
    """An open `0.1.*` range makes "no further change in views-hydranet" unfalsifiable.

    This asserts a policy the claim depends on rather than a bug in the code: that a source
    whose results are compared across runs names the version it was validated against. If the
    policy is rejected, delete this test — but then the claim's third clause cannot be
    asserted either, because the library version is not under the repo's control.
    """
    specs = {}
    for d in HYDRANET_SOURCES:
        text = (d / "requirements.txt").read_text()
        m = re.search(r"^(views-hydranet\S*)", text, re.MULTILINE)
        if m:
            specs.setdefault(m.group(1), []).append(d.name)

    assert specs, "found no views-hydranet specifier at all — refusing to pass"

    open_ranges = {
        spec: sorted(names)
        for spec, names in specs.items()
        if "~=" in spec or ("==" not in spec)
    }

    assert not open_ranges or EXPECTED_HYDRANET_SPEC_IS_EXACT, (
        f"{sum(len(v) for v in open_ranges.values())} source(s) pin views-hydranet with a "
        f"range that admits versions they were never run against:\n"
        + "\n".join(f"  {s}  <- {v}" for s, v in open_ranges.items())
        + "\nPyPI held 0.1.7 on 2026-10-24 (published 2026-10-23); envs/views-hydranet holds "
        "0.1.5. A fresh env and this env run different code from the same config."
    )
