def test_spotlight_is_defined_or_pointed_at_on_first_use():
    """F4: "Spotlight" appears eight times in Section 2 and is defined in Section 5."""
    models = (SECTIONS / "the_models.tex").read_text(encoding="utf-8")
    assert "Spotlight" not in models or "sec:losses" in models, (
        "Section 2 uses 'Spotlight' without defining it or pointing forward"
    )


def test_the_file_format_is_explained():
    """F5: 'Parquet' is named once with no indication of how to open it.

    The reading instruction went with the deleted Consuming the Delivery
    section.
    """
    prose = _all_prose()
    assert "Parquet" not in prose or "read\\_parquet" in prose, (
        "the delivered file format is named but never explained"
    )


@pytest.mark.parametrize("term", ["recurrence", "convolution", "attention"])
def test_no_undefined_term_appears_only_in_the_negative(term):
    """F6: "None uses recurrence, convolution or attention."

    Three terms the reader does not know, named only to say they are absent.
    That conveys nothing to him and costs three unfamiliar words.
    """
    prose = _all_prose()
    if term not in prose:
        return
    assert prose.count(term) > 1, (
        f"{term!r} appears once, in a list of things the models do not use"
    )


def test_spectral_term_is_explained():
    """F7: "a weight on a spectral term" — the term is never defined."""
    losses = (SECTIONS / "losses.tex").read_text(encoding="utf-8")
    assert "spectral" not in losses or "spectral term is" in losses, (
        "'spectral term' is used without explanation"
    )
