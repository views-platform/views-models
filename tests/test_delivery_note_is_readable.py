"""Falsification stubs for the darts delivery note (2026-10-10).

Generated by /falsify against the claim that every section is clear, precise,
concrete, well structured and readable by the recipient: a strong statistician
with no machine-learning or software background.

Every test here FAILS at the time of writing and documents one falsification.
They assert on the LaTeX sources rather than the PDF, so they are cheap and
they point at the file that needs editing.
"""

from __future__ import annotations

from pathlib import Path

import pytest

NOTE = (
    Path(__file__).resolve().parents[1]
    / "reports/delivery_notes/r2darts2-pgm-global-calibration-2026-10"
)
SECTIONS = NOTE / "sections"


def _all_prose() -> str:
    return "\n".join(p.read_text(encoding="utf-8") for p in sorted(SECTIONS.glob("*.tex")))


# --------------------------------------------------------------------------
# HARD falsifications
# --------------------------------------------------------------------------

def test_count_scale_claim_is_hedged_not_asserted():
    """F1: the note asserts the columns ARE on the count scale.

    Nothing verifies the inversion. An earlier revision said "intended to be"
    and carried a paragraph distinguishing the magnitude check from a proof;
    the trim that moved the examination agenda to #548 removed both. The note
    now states as fact the one thing in it that is assumed.
    """
    text = (SECTIONS / "transformations.tex").read_text(encoding="utf-8")
    assert "intended to be on the original count scale" in text, (
        "the count-scale claim is asserted rather than hedged; the inversion "
        "is not verified anywhere in the delivery"
    )


def test_the_note_asks_the_recipient_for_something():
    """F2: three decisions are needed from the recipient and none is asked.

    Column naming, which September variant the evaluation was built on, and
    whether cell 148759 is a real event — all three appear only as statements
    inside Caveats. The Markdown version had a "What I need from you" section;
    it did not survive the port to LaTeX.
    """
    main = (NOTE / "main.tex").read_text(encoding="utf-8")
    assert any(
        marker in main
        for marker in ("What I Need", "Questions", "Requested", "Next Steps")
    ), "no section asks the recipient for anything"


def test_the_document_has_a_closing_section():
    """F3: the note ends on the bibliography.

    The house release notes close with "Next Steps and Conclusion". This one
    stops after References, with no statement of what happens next.
    """
    main = (NOTE / "main.tex").read_text(encoding="utf-8")
    body = main[main.index(r"\section{Context}"):]
    last = [ln for ln in body.splitlines() if ln.startswith(r"\section")][-1]
    assert "Conclusion" in last or "Next Steps" in last, (
        f"document ends on {last!r}, not a closing section"
    )


